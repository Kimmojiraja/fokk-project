    /**
     * Categorizes a bullet point into FACT, CLAIM, or OPINION.
     */
    fun classifyBullet(text: String): String {
        val t = text.lowercase(Locale.ROOT)
        val hasFactualMarkers = Regex("""\b(?:jailed|sentenced|arrested|convicted|pleaded|announced|confirmed|published|appointed|died|founded|ruled|voted|signed|acquired|passed|established|found|showed|data|research|budget|£\d+|\$\d+|\d+%|\d+\s*(?:million|billion|thousand|years?|months?|days?))\b""").containsMatchIn(t)
        val hasOpinionKeywords = Regex("""\b(?:impressive|masterclass|disaster|amazing|incredible|appalling|shocking|disgraceful|outrageous|arguably|perhaps|believe|pundit|opinion|feels|seems|awful|terrible|criticised|criticized)\b""").containsMatchIn(t)
        val hasClaimKeywords = Regex("""\b(?:claims?|claimed|alleged|allegations?|promised|rumored|sources say|according to|set to|disputed|unconfirmed|proposed)\b""").containsMatchIn(t)

        return when {
            hasOpinionKeywords && !hasFactualMarkers -> "OPINION"
            hasFactualMarkers && !hasClaimKeywords -> "FACT"
            hasClaimKeywords -> "CLAIM"
            hasFactualMarkers -> "FACT"
            else -> "CLAIM"
        }
    }

    /**
     * Deterministic baseline credibility assessment with accurate provenance detection
     * (never matching generic lowercase phrases like "the party leader").
     */
    fun evaluateCredibility(
        host: String,
        title: String,
        context: String,
        sources: List<CorroboratedSource>,
        tagScore: Int? = null,
        tagVerdict: String = ""
    ): CredibilityAssessment {
        val normHost = host.lowercase(Locale.ROOT).removePrefix("www.")
        val publisherLabel = if (normHost.isNotBlank()) FokkSearchAggregator.cleanPublisherName(normHost) else "this site"
        val isSocialAggregator = normHost.contains("x.com") || normHost.contains("twitter.com") ||
                normHost.contains("reddit.com") || normHost.contains("threads.net") || normHost.contains("bsky.app")
        val isReputableHost = FokkSearchAggregator.isReputableDomain(normHost)

        val combinedText = "$title $context".lowercase(Locale.ROOT)

        // Strictly detect ONLY real known outlets when explicitly attributed or on an aggregator
        val detectedOriginalSource = if (isSocialAggregator) {
            KNOWN_OUTLETS.firstOrNull { outlet ->
                combinedText.contains(outlet.lowercase(Locale.ROOT))
            }.orEmpty()
        } else {
            val attrMatch = Regex("""(?:first reported by|citing|originally published by|reported by)\s+(The\s+[A-Z][a-z]+(?:\s+[A-Z][a-z]+)?|[A-Z][a-zA-Z]+(?:\s+[A-Z][a-zA-Z]+)?)""")
                .find("$title $context")
            val candidate = attrMatch?.groupValues?.get(1)?.trim().orEmpty()
            KNOWN_OUTLETS.firstOrNull { outlet ->
                candidate.equals(outlet, ignoreCase = true) && !publisherLabel.equals(outlet, ignoreCase = true)
            }.orEmpty()
        }

        val aggregatorSource = when {
            normHost.contains("x.com") || normHost.contains("twitter.com") -> "X (Twitter)"
            normHost.contains("reddit.com") -> "Reddit"
            normHost.contains("youtube.com") || normHost == "youtu.be" -> "YouTube"
            isSocialAggregator -> "Social Platform"
            else -> ""
        }

        val isOfficialAnnouncement = combinedText.contains("official statement") ||
                combinedText.contains("press release") ||
                combinedText.contains("sec filing") ||
                combinedText.contains("court ruling") ||
                combinedText.contains("official announcement") ||
                combinedText.contains("ministry of justice")

        val reputableSourcesCount = sources.count { s ->
            s.sourceType == "NEWS" || FokkSearchAggregator.isReputableDomain(s.domain)
        }

        val computed = when {
            isOfficialAnnouncement && (isReputableHost || reputableSourcesCount >= 1) -> {
                Triple(
                    94,
                    "Officially Confirmed",
                    "Backed by an official announcement, institutional record, or court ruling."
                )
            }
            reputableSourcesCount >= 3 || (isReputableHost && sources.size >= 2) -> {
                val s = minOf(92, 82 + minOf(reputableSourcesCount * 3, 10))
                Triple(
                    s,
                    "Verified Multi-Source Reporting",
                    "Corroborated across independent newsrooms alongside $publisherLabel."
                )
            }
            isReputableHost -> {
                Triple(
                    82,
                    "Established Editorial Source",
                    "Published directly by $publisherLabel, a recognized newsroom with editorial oversight."
                )
            }
            sources.size in 1..2 -> {
                Triple(
                    74,
                    "Limited Corroboration",
                    "Matched by ${sources.size} external source${if (sources.size > 1) "s" else ""}; broader verification is still developing."
                )
            }
            isSocialAggregator -> {
                Triple(
                    45,
                    "Social Post · Unverified",
                    "Shared on $aggregatorSource; check primary reporting before treating claims as confirmed."
                )
            }
            else -> {
                Triple(
                    68,
                    "Direct Web Source",
                    "Published directly by $publisherLabel; independent cross-checks are limited."
                )
            }
        }

        val finalScore = tagScore?.coerceIn(15, 98) ?: computed.first
        val finalVerdict = if (tagVerdict.isNotBlank() && tagVerdict.length <= 42) tagVerdict else computed.second
        val finalReason = computed.third

        val l1 = if (isSocialAggregator) {
            val orig = if (detectedOriginalSource.isNotBlank()) " referencing $detectedOriginalSource" else ""
            "Hosted on $aggregatorSource ($normHost) — a social platform rather than a primary newsroom$orig."
        } else if (isReputableHost) {
            "Published directly on $publisherLabel ($normHost), an established publication over verified HTTPS."
        } else {
            "Published directly on $publisherLabel ($normHost) over HTTPS; verify author and primary citations independently."
        }

        val loadedWords = listOf("bombshell", "shock move", "masterclass", "disaster", "embarrassing", "furious", "unbelievable", "crisis", "slams", "humiliating", "outrage", "appalling")
        val foundLoaded = loadedWords.filter { combinedText.contains(it) }
        val l2 = when {
            foundLoaded.isNotEmpty() -> "Uses emphatic or emotionally charged terms (${foundLoaded.take(3).joinToString(", ") { "'$it'" }}). Separate core facts from editorial framing."
            isSocialAggregator -> "Short-form social framing optimized for engagement; often omits full context and nuance."
            else -> "Structured informational reporting with measured language and clear attribution."
        }

        val l3 = if (sources.isNotEmpty()) {
            val topNames = sources.take(3).map { FokkSearchAggregator.cleanPublisherName(it.domain) }.distinct().joinToString(", ")
            "Cross-checked against ${sources.size} external source${if (sources.size > 1) "s" else ""} including $topNames."
        } else {
            "Analyzed from the active page text; no additional external newsroom matches were returned."
        }

        val whatsMissing = when {
            isOfficialAnnouncement -> ""
            sources.size >= 3 -> ""
            isReputableHost && sources.isEmpty() -> "Independent follow-up coverage from additional newsrooms has not been linked yet."
            isSocialAggregator -> "Original primary documentation or a full newsroom report is not attached directly to this post."
            sources.isEmpty() -> "Broader independent confirmation from other outlets is currently limited."
            else -> ""
        }

        return CredibilityAssessment(
            score = finalScore,
            verdict = finalVerdict,
            reason = finalReason,
            isAggregator = isSocialAggregator,
            originalSource = detectedOriginalSource,
            aggregatorSource = aggregatorSource,
            layer1 = l1,
            layer2 = l2,
            layer3 = l3,
            whatsMissing = whatsMissing
        )
    }

    /**
     * Extracts contextual KeyMetric items (value + meaningful short label) from raw text
     * when the LLM is offline or didn't supply metrics. Skips contextless standalone years.
     */
    fun extractContextualMetrics(text: String, max: Int = 4): List<KeyMetric> {
        if (text.isBlank()) return emptyList()
        val clean = cleanDropCaps(text)
        val results = mutableListOf<KeyMetric>()
        val seenValues = mutableSetOf<String>()

        // Match currency, percentages, or large quantities alongside surrounding words
        val regex = Regex("""([£$€]\s?\d+(?:[.,]\d+)?\s?(?:billion|million|trillion|bn|mn|m|k|b)?|\d+(?:\.\d+)?%|\b\d+(?:,\d{3})+\b)\s+([a-zA-Z][a-zA-Z\s\-]{3,36})""")
        for (match in regex.findAll(clean)) {
            val rawVal = match.groupValues[1].trim()
            val normVal = rawVal.lowercase(Locale.ROOT)
            if (seenValues.contains(normVal)) continue

            // Clean trailing words into a short 2-5 word label
            val rawPhrase = match.groupValues[2]
                .split(Regex("[,.;:()—–]|\\band\\b|\\bbut\\b|\\bwhich\\b|\\bthat\\b|\\bwhile\\b|\\bfrom\\b|\\bin\\b"))
                .firstOrNull()?.trim().orEmpty()
            val labelWords = rawPhrase.split(Regex("\\s+")).filter { it.isNotBlank() }.take(4)
            if (labelWords.size >= 2) {
                val label = labelWords.joinToString(" ").replaceFirstChar { it.uppercase() }
                seenValues.add(normVal)
                results.add(KeyMetric(rawVal, label))
                if (results.size >= max) break
            }
        }
        return results
    }

    /**
     * Parses the structured LLM output into a FokkAiAnalysis object.
     */
    private fun parseAnalysisOutput(
        rawOutput: String,
        sources: List<CorroboratedSource>,
        title: String,
        host: String,
        pageContext: String
    ): FokkAiAnalysis {
        val sanitized = sanitizeLlmOutput(rawOutput)
        val splitFollowups = sanitized.split(Regex("(?i)SUGGESTED_FOLLOWUPS:"))
        val mainBody = splitFollowups[0].trim()
        val followUps = if (splitFollowups.size > 1) {
            splitFollowups[1].trim().split(Regex("[|\n]"))
                .map { it.trim().removePrefix("-").removePrefix("*").removePrefix("•").trim() }
                .filter { it.isNotBlank() && it.length > 8 && !it.startsWith("SUGGESTED", ignoreCase = true) }
                .take(3)
        } else {
            buildContextualFollowUps(title, "")
        }

        fun extractTag(tag: String): String {
            val m = Regex("(?is)(?:\\*\\*)?${tag}(?:\\*\\*)?\\s*:\\s*(.*?)(?=(?:\\*\\*)?(?:SCORE|VERDICT|BIAS_POSITION|BIAS|SENSATIONALISM|LAYER1_DOMAIN|LAYER2_STANCE|LAYER3_EVIDENCE|COUNTER_PERSPECTIVE|WHATS_MISSING|VISUAL_ENTITIES|KEY_EVIDENCE|KEY_METRICS|EXECUTIVE_BRIEF|TRUTH_AUDIT|SUGGESTED_FOLLOWUPS)(?:\\*\\*)?:|$)").find(mainBody)
            return m?.groupValues?.get(1)?.trim().orEmpty()
        }

        val tagExec = extractTag("EXECUTIVE_BRIEF")
        val tagKeyEvidence = extractTag("KEY_EVIDENCE")
        val tagKeyMetrics = extractTag("KEY_METRICS")
        val tagScore = extractTag("SCORE").filter { it.isDigit() }.toIntOrNull()
        val tagVerdict = extractTag("VERDICT").lines().firstOrNull()?.trim().orEmpty()
        val tagBias = extractTag("BIAS").lines().firstOrNull()?.trim().orEmpty()
        val tagBiasPos = extractTag("BIAS_POSITION").filter { it.isDigit() }.toIntOrNull()
        val tagSensationalism = extractTag("SENSATIONALISM").filter { it.isDigit() }.toIntOrNull()
        val tagL1 = extractTag("LAYER1_DOMAIN")
        val tagL2 = extractTag("LAYER2_STANCE")
        val tagL3 = extractTag("LAYER3_EVIDENCE")
        val tagCounter = extractTag("COUNTER_PERSPECTIVE")
        val tagMissing = extractTag("WHATS_MISSING")
        val tagVisualEntities = extractTag("VISUAL_ENTITIES")

        val bulletSource = if (tagKeyEvidence.isNotBlank()) tagKeyEvidence else mainBody
        val bulletPoints = bulletSource.split("\n")
            .map { it.trim() }
            .filter {
                (it.startsWith("-") || it.startsWith("*") || it.startsWith("•") || Regex("""^\d+\.""").containsMatchIn(it)) &&
                    !it.contains("SUGGESTED_FOLLOWUPS", ignoreCase = true) &&
                    !it.contains("::")
            }
            .map { it.replace(Regex("""^[-•\d.\s]+"""), "").trim().removePrefix("* ").trim() }
            .filter {
                it.length > 15 &&
                    !it.startsWith("SCORE", ignoreCase = true) &&
                    !it.startsWith("VERDICT", ignoreCase = true)
            }
            .take(4)

        // Parse contextual key metrics ("VALUE :: LABEL")
        val parsedMetrics = mutableListOf<KeyMetric>()
        if (tagKeyMetrics.isNotBlank() && !tagKeyMetrics.equals("NONE", ignoreCase = true)) {
            tagKeyMetrics.lines().forEach { line ->
                val cleaned = line.trim().removePrefix("-").removePrefix("*").removePrefix("•").trim()
                if (cleaned.contains("::")) {
                    val parts = cleaned.split("::", limit = 2)
                    val v = parts[0].replace("**", "").trim()
                    val l = parts[1].replace("**", "").trim().trimEnd('.')
                    if (v.isNotBlank() && l.isNotBlank() && v.length <= 24 && !v.equals("NONE", ignoreCase = true)) {
                        parsedMetrics.add(KeyMetric(v, l))
                    }
                }
            }
        }
        val finalMetrics = if (parsedMetrics.isNotEmpty()) {
            parsedMetrics.take(4)
        } else {
            extractContextualMetrics(pageContext, max = 4)
        }

        val execBrief = when {
            tagExec.isNotBlank() -> tagExec
            else -> {
                mainBody.split("\n").map { it.trim() }.firstOrNull { l ->
                    !l.startsWith("#") && !l.startsWith("-") && !l.startsWith("*") &&
                        !l.startsWith("SCORE", ignoreCase = true) && !l.startsWith("VERDICT", ignoreCase = true) &&
                        !l.startsWith("EXECUTIVE", ignoreCase = true) && !l.startsWith("TRUTH_AUDIT", ignoreCase = true) &&
                        l.length > 35
                } ?: "Summary synthesized for $title."
            }
        }

        val assessment = evaluateCredibility(host, title, "$mainBody $pageContext", sources, tagScore, tagVerdict)
        val finalBias = if (tagBias.isNotBlank() && tagBias.length <= 36) tagBias else "Objective Reporting"
        val finalL1 = if (tagL1.isNotBlank()) tagL1 else assessment.layer1
        val finalL2 = if (tagL2.isNotBlank()) tagL2 else assessment.layer2
        val finalL3 = if (tagL3.isNotBlank()) tagL3 else assessment.layer3
        val finalMissing = when {
            tagMissing.equals("NONE", ignoreCase = true) -> ""
            tagMissing.isNotBlank() -> tagMissing
            else -> assessment.whatsMissing
        }

        val finalCounter = when {
            tagCounter.equals("NONE", ignoreCase = true) -> ""
            tagCounter.isNotBlank() -> tagCounter
            else -> ""
        }
        val finalEntities = tagVisualEntities
            .split(Regex("[|,\n]"))
            .map { it.trim().removePrefix("-").removePrefix("*").trim() }
            .filter { it.length in 3..55 && !it.equals("NONE", ignoreCase = true) }
            .distinct()
            .take(4)

        val inferredBiasPos = tagBiasPos?.coerceIn(5, 95) ?: when {
            finalBias.contains("far left", ignoreCase = true) -> 15
            finalBias.contains("left", ignoreCase = true) -> 30
            finalBias.contains("far right", ignoreCase = true) -> 85
            finalBias.contains("right", ignoreCase = true) -> 70
            else -> 50
        }
        val inferredSensationalism = tagSensationalism?.coerceIn(0, 100) ?: 18

        val finalBullets = if (bulletPoints.isNotEmpty()) bulletPoints else listOf(execBrief)
        val tagged = finalBullets.map { TaggedEvidencePoint(it, classifyBullet(it)) }

        return FokkAiAnalysis(
            executiveBrief = execBrief,
            keyEvidencePoints = finalBullets,
            fullAnalysis = mainBody,
            credibilityScore = assessment.score,
            credibilityVerdict = assessment.verdict,
            credibilityReason = assessment.reason,
            biasTone = finalBias,
            corroboratedSources = sources,
            verifiedClaims = finalBullets.take(4),
            followUpQuestions = followUps,
            layer1DomainIdentity = finalL1,
            layer2RhetoricalStance = finalL2,
            layer3EvidenceDensity = finalL3,
            originalSource = assessment.originalSource,
            aggregatorSource = assessment.aggregatorSource,
            isAggregator = assessment.isAggregator,
            whatsMissing = finalMissing,
            taggedBullets = tagged,
            keyMetrics = finalMetrics,
            biasPosition = inferredBiasPos,
            sensationalismScore = inferredSensationalism,
            counterPerspective = finalCounter,
            visualEntities = finalEntities
        )
    }

    /**
     * On-demand Reading Depth transformer ("ELI5" or "DEEP") for the Summary tab.
     */
    suspend fun rewriteSummaryDepth(
        context: Context,
        mode: String,
        pageTitle: String,
        pageHost: String,
        pageContext: String
    ): String = withContext(Dispatchers.IO) {
        val apiKey = resolveApiKey(context)
        val cleanCtx = cleanDropCaps(pageContext).take(7500)
        val isEli5 = mode.equals("ELI5", ignoreCase = true)
        val systemPrompt = if (isEli5) {
            """
            You are Fokk AI. Explain this page in crystal-clear, everyday plain English (Explain Like I'm 5 style) without being condescending.
            - Use 2 short paragraphs or 3 simple bullet points with relatable everyday analogies.
            - Avoid jargon; if a technical or political term is needed, explain it in parentheses.
            - Strictly ZERO emojis. No preamble.
            """.trimIndent()
        } else {
            """
            You are Fokk AI, a senior strategic analyst. Deliver a sharp Deep Dive into this page.
            - Go beyond the surface summary: explain WHY this matters, second-order implications, incentives of the key players, and what to watch next.
            - Format as 3 concise analytical bullets with **bold lead-ins**.
            - Strictly ZERO emojis. No preamble.
            """.trimIndent()
        }
        val userQuery = "Title: $pageTitle ($pageHost)\n\nContent:\n$cleanCtx"
        val raw = queryInferencePipeline(apiKey, systemPrompt, userQuery)
        if (raw.isNotBlank()) {
            sanitizeLlmOutput(raw)
        } else {
            if (isEli5) {
                "In simple terms: $pageTitle covers key developments reported by ${FokkSearchAggregator.cleanPublisherName(pageHost)}. Try again when connected to load the full simplified breakdown."
            } else {
                "Deep analysis requires live AI connectivity. Re-tap Deep once your connection stabilizes."
            }
        }
    }

    /**
     * Synthesizes a clean on-device analysis when cloud LLMs are unavailable.
     */
    fun synthesizeOfflineAnalysis(
        title: String,
        host: String,
        pageContext: String,
        sources: List<CorroboratedSource>,
        pageAuthor: String = "",
        pagePublished: String = ""
    ): FokkAiAnalysis {
        val cleanContext = cleanDropCaps(pageContext)
        val sentences = cleanContext.split(Regex("(?<=[.!?])\\s+"))
            .map { it.trim() }
            .filter { it.length in 35..340 }
            .distinct()

        val lead = sentences.take(2).joinToString(" ").ifBlank {
            "Content extracted directly from ${FokkSearchAggregator.cleanPublisherName(host)}."
        }

        val bodySentences = sentences.drop(1)
        val dataSentences = bodySentences.filter { s ->
            Regex("""[£$€]\d+|\d+%|\b(?:million|billion|research|study|found|report|confirmed)\b""", RegexOption.IGNORE_CASE).containsMatchIn(s)
        }.take(3)

        val bullets = (if (dataSentences.size >= 2) dataSentences else bodySentences.take(3))
            .ifEmpty { sentences.take(3) }
        val tagged = bullets.map { TaggedEvidencePoint(it, classifyBullet(it)) }
        val metrics = extractContextualMetrics(cleanContext, max = 4)
        val assessment = evaluateCredibility(host, title, cleanContext, sources)

        return FokkAiAnalysis(
            executiveBrief = lead,
            keyEvidencePoints = bullets,
            fullAnalysis = lead,
            credibilityScore = assessment.score,
            credibilityVerdict = assessment.verdict,
            credibilityReason = assessment.reason,
            biasTone = "Informational",
            corroboratedSources = sources,
            verifiedClaims = bullets.take(3),
            followUpQuestions = listOf(
                "What are the main findings in this article?",
                "Who published this and what sources do they cite?",
                "What counterarguments or missing context should I know?"
            ),
            layer1DomainIdentity = assessment.layer1,
            layer2RhetoricalStance = assessment.layer2,
            layer3EvidenceDensity = assessment.layer3,
            originalSource = assessment.originalSource,
            aggregatorSource = assessment.aggregatorSource,
            isAggregator = assessment.isAggregator,
            whatsMissing = assessment.whatsMissing,
            taggedBullets = tagged,
            keyMetrics = metrics
        )
    }

    /**
     * Intent-aware offline synthesis so even completely offline Ask AI gives tailored,
     * non-repetitive answers to different questions ("who posted it", "what is this", numbers, etc.).
     */
    fun buildOfflineForensicSynthesis(
        query: String,
        pageContext: String,
        sources: List<CorroboratedSource>,
        pageTitle: String = "",
        pageHost: String = "",
        pageAuthor: String = "",
        pagePublished: String = ""
    ): String {
        val cleanContext = cleanDropCaps(pageContext)
        val qLower = query.lowercase(Locale.ROOT).trim()
        val publisher = if (pageHost.isNotBlank()) FokkSearchAggregator.cleanPublisherName(pageHost) else "this webpage"
        val sentences = cleanContext.split(Regex("(?<=[.!?])\\s+"))
            .map { it.trim() }
            .filter { it.length > 25 && !it.startsWith("Want to bookmark", ignoreCase = true) }
            .take(100)

        val sb = StringBuilder()

        // Intent 1: Who posted / wrote / published this?
        val asksWho = Regex("""\b(who\s+(posted|wrote|published|made|created)|author|publisher|source|byline)\b""").containsMatchIn(qLower)
        // Intent 2: When was this published?
        val asksWhen = Regex("""\b(when\s+(was|did)|date|published)\b""").containsMatchIn(qLower)
        // Intent 3: Numbers / figures / stats?
        val asksNumbers = Regex("""\b(number|figure|stat|cost|much|percent|how many|data|budget|money)\b""").containsMatchIn(qLower)
        // Intent 4: Fact-check / true / bias / reliable?
        val asksVerify = Regex("""\b(true|real|fake|fact|bias|reliable|credible|verify|trust)\b""").containsMatchIn(qLower)

        when {
            asksWho -> {
                sb.append("This page was published by **$publisher**")
                if (pageHost.isNotBlank()) sb.append(" (`$pageHost`)")
                if (pageAuthor.isNotBlank()) sb.append(", credited to **$pageAuthor**")
                if (pagePublished.isNotBlank()) sb.append(" on **$pagePublished**")
                sb.append(".\n\n")
                if (pageTitle.isNotBlank()) {
                    sb.append("**Topic:** $pageTitle\n\n")
                }
                if (sentences.isNotEmpty()) {
                    sb.append(sentences.first().trimEnd('.')).append(".\n")
                }
            }
            asksWhen -> {
                if (pagePublished.isNotBlank()) {
                    sb.append("This article was published on **$pagePublished** by **$publisher**.\n\n")
                } else {
                    sb.append("No explicit publication timestamp was exposed in this page's metadata by **$publisher**.\n\n")
                }
                val dateSentences = sentences.filter { Regex("""\b(20\d{2}|January|February|March|April|May|June|July|August|September|October|November|December|yesterday|today|last year|months?)\b""", RegexOption.IGNORE_CASE).containsMatchIn(it) }.take(2)
                dateSentences.forEach { sb.append("- ${it.trimEnd('.')}.\n") }
            }
            asksNumbers -> {
                val metrics = extractContextualMetrics(cleanContext, max = 5)
                if (metrics.isNotEmpty()) {
                    sb.append("Here are the key figures mentioned on this page:\n\n")
                    metrics.forEach { m -> sb.append("- **${m.value}** — ${m.label}\n") }
                } else {
                    val numSentences = sentences.filter { Regex("""\d""").containsMatchIn(it) }.take(3)
                    sb.append("Key quantitative details from the page:\n\n")
                    numSentences.forEach { sb.append("- ${it.trimEnd('.')}.\n") }
                }
            }
            asksVerify -> {
                val assessment = evaluateCredibility(pageHost, pageTitle, cleanContext, sources)
                sb.append("**Assessment:** ${assessment.verdict} (${assessment.score}%)\n\n")
                sb.append("${assessment.reason}\n\n")
                sb.append("- **Source:** ${assessment.layer1}\n")
                sb.append("- **Framing:** ${assessment.layer2}\n")
                sb.append("- **Corroboration:** ${assessment.layer3}\n")
            }
            else -> {
                // Dynamic Multi-Source Relevance Scoring (Objective TF / Keyword Coverage)
                val queryWords = qLower.split(Regex("[^a-z0-9]+"))
                    .filter { it.isNotBlank() && !FokkSearchAggregator.isFunctionalStopWord(it) }

                val scoredSentences = if (queryWords.isNotEmpty()) {
                    sentences.map { s ->
                        val lowerS = s.lowercase(Locale.ROOT)
                        val hits = queryWords.count { lowerS.contains(it) }
                        Pair(s, hits)
                    }.filter { it.second > 0 }.sortedByDescending { it.second }
                } else {
                    emptyList()
                }

                val scoredSources = if (queryWords.isNotEmpty()) {
                    sources.map { src ->
                        val text = "${src.title} ${src.snippet}".lowercase(Locale.ROOT)
                        val hits = queryWords.count { text.contains(it) }
                        Pair(src, hits)
                    }.sortedByDescending { it.second }
                } else {
                    sources.map { Pair(it, 0) }
                }

                val bestPageHits = scoredSentences.firstOrNull()?.second ?: 0
                val bestSourceHits = scoredSources.firstOrNull()?.second ?: 0

                // If external live sources match more query keywords than the active page context,
                // or if page context has zero matches for the query, prioritize live web sources!
                val preferLiveSources = sources.isNotEmpty() && (bestSourceHits > bestPageHits || bestPageHits == 0)

                if (preferLiveSources) {
                    sb.append("Based on live sources:\n\n")
                    scoredSources.map { it.first }.take(3).forEachIndexed { i, src ->
                        sb.append("- **${src.title}** (${FokkSearchAggregator.cleanPublisherName(src.domain)}) [${i + 1}]")
                        if (src.snippet.isNotBlank()) sb.append(": ${src.snippet}")
                        sb.append("\n")
                    }
                } else if (scoredSentences.isNotEmpty()) {
                    sb.append("Based on **$publisher**:\n\n")
                    scoredSentences.map { it.first }.take(3).forEach { s -> sb.append("- ${s.trimEnd('.')}.\n") }
                } else if (sources.isNotEmpty()) {
                    sb.append("Based on live sources:\n\n")
                    sources.take(3).forEachIndexed { i, src ->
                        sb.append("- **${src.title}** (${FokkSearchAggregator.cleanPublisherName(src.domain)}) [${i + 1}]")
                        if (src.snippet.isNotBlank()) sb.append(": ${src.snippet}")
                        sb.append("\n")
                    }
                } else if (sentences.isNotEmpty()) {
                    if (pageTitle.isNotBlank()) {
                        sb.append("**$pageTitle** (*$publisher*)\n\n")
                    }
                    sb.append(sentences.first().trimEnd('.')).append(".\n\n")
                    sentences.drop(1).take(2).forEach { s -> sb.append("- ${s.trimEnd('.')}.\n") }
                } else {
                    sb.append("I couldn't reach live AI servers right now and there isn't enough text on this page to answer that fully. Try again in a moment.")
                }
            }
        }

        val followUps = buildContextualFollowUps(pageTitle, query)
        sb.append("\nSUGGESTED_FOLLOWUPS: ").append(followUps.joinToString(" | "))
        return sb.toString()
    }

    /**
     * Kept for backward compatibility with any callers referencing stripEmojis.
     */
    fun stripEmojis(text: String): String {
        if (text.isEmpty()) return ""
        val sb = StringBuilder(text.length)
        var i = 0
        while (i < text.length) {
            val cp = text.codePointAt(i)
            val charCount = Character.charCount(cp)
            val isEmoji = (cp in 0x1F300..0x1FAFF) ||
                (cp in 0x1F600..0x1F64F) ||
                (cp in 0x2600..0x27BF) ||
                (cp in 0xFE00..0xFE0F) ||
                (cp in 0x1F900..0x1F9FF) ||
                (cp in 0x1F1E6..0x1F1FF) ||
                (cp in 0x2300..0x23FF) ||
                (cp == 0x2B50) || (cp == 0x2B55) || (cp == 0x200D)
            if (!isEmoji) {
                sb.appendCodePoint(cp)
            }
            i += charCount
        }
        return sb.toString().trim()
    }
