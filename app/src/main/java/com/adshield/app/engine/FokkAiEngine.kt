    }

    private fun buildContextualFollowUps(pageTitle: String, lastQuery: String): List<String> {
        val qLower = lastQuery.lowercase(Locale.ROOT)
        val list = mutableListOf<String>()
        if (!qLower.contains("takeaway") && !qLower.contains("summary")) {
            list.add("What are the key takeaways in 3 bullet points?")
        }
        if (!qLower.contains("bias") && !qLower.contains("true") && !qLower.contains("fact")) {
            list.add("Are there any unsupported claims or missing perspectives here?")
        }
        if (!qLower.contains("impact") && !qLower.contains("next")) {
            list.add("What happens next or why does this matter?")
        }
        return list.take(2)
    }

    /**
     * Tries available API endpoints with fast failover.
     */
    private fun queryInferencePipeline(
        apiKey: String,
        systemPrompt: String,
        userQuery: String,
        conversationHistory: List<Pair<String, String>> = emptyList()
    ): String {
        if (apiKey.isBlank()) return ""

        // Direct Google Gemini API if user provided an AIza key
        if (apiKey.startsWith("AIza", ignoreCase = true)) {
            for (model in GEMINI_MODELS) {
                val geminiResp = callGeminiDirectApi(apiKey, systemPrompt, userQuery, conversationHistory, model)
                if (geminiResp.isNotBlank()) return geminiResp
            }
        }

        // OpenRouter inference with verified fast models + future-proof free router fallback
        for (model in FAILOVER_MODELS) {
            val disableReasoning = model != "openrouter/free" && !model.startsWith("google/gemma")
            val resp = callOpenRouterEndpoint(
                apiKey = apiKey,
                systemPrompt = systemPrompt,
                userQuery = userQuery,
                model = model,
                conversationHistory = conversationHistory,
                disableReasoning = disableReasoning
            )
            if (resp.isNotBlank()) return resp
        }

        return ""
    }

    /**
     * Direct call to Google Gemini API.
     */
    private fun callGeminiDirectApi(
        apiKey: String,
        systemPrompt: String,
        userQuery: String,
        conversationHistory: List<Pair<String, String>> = emptyList(),
        model: String = "gemini-2.5-flash"
    ): String {
        return try {
            val endpoint = "https://generativelanguage.googleapis.com/v1beta/models/$model:generateContent?key=$apiKey"
            val contents = JSONArray()

            // Add recent conversation turns
            conversationHistory.takeLast(6).forEach { (q, a) ->
                contents.put(JSONObject().apply {
                    put("role", "user")
                    put("parts", JSONArray().put(JSONObject().put("text", q)))
                })
                contents.put(JSONObject().apply {
                    put("role", "model")
                    put("parts", JSONArray().put(JSONObject().put("text", a.take(1200))))
                })
            }

            contents.put(JSONObject().apply {
                put("role", "user")
                put("parts", JSONArray().put(JSONObject().put("text", userQuery)))
            })

            val body = JSONObject().apply {
                put("system_instruction", JSONObject().apply {
                    put("parts", JSONArray().put(JSONObject().put("text", systemPrompt)))
                })
                put("contents", contents)
                put("generationConfig", JSONObject().apply {
                    put("temperature", 0.35)
                    put("maxOutputTokens", 1400)
                })
            }.toString().toByteArray(StandardCharsets.UTF_8)

            val conn = (URL(endpoint).openConnection() as HttpURLConnection).apply {
                requestMethod = "POST"
                setRequestProperty("Content-Type", "application/json")
                connectTimeout = DEFAULT_CONNECT_TIMEOUT
                readTimeout = DEFAULT_READ_TIMEOUT
                doOutput = true
            }

            conn.outputStream.use { it.write(body) }

            if (conn.responseCode == HttpURLConnection.HTTP_OK) {
                val resp = conn.inputStream.bufferedReader(StandardCharsets.UTF_8).use { it.readText() }
                val root = JSONObject(resp)
                val candidates = root.optJSONArray("candidates") ?: return ""
                if (candidates.length() == 0) return ""
                val parts = candidates.getJSONObject(0).optJSONObject("content")?.optJSONArray("parts") ?: return ""
                if (parts.length() == 0) return ""
                val text = parts.getJSONObject(0).optString("text", "")
                sanitizeLlmOutput(text)
            } else {
                ""
            }
        } catch (_: Exception) {
            ""
        }
    }

    /**
     * Queries OpenRouter chat completions endpoint with multi-turn messages.
     */
    private fun callOpenRouterEndpoint(
        apiKey: String,
        systemPrompt: String,
        userQuery: String,
        model: String,
        conversationHistory: List<Pair<String, String>> = emptyList(),
        disableReasoning: Boolean = true
    ): String {
        return try {
            val endpoint = "https://openrouter.ai/api/v1/chat/completions"
            val messages = JSONArray().apply {
                put(JSONObject().apply {
                    put("role", "system")
                    put("content", systemPrompt)
                })
                conversationHistory.takeLast(6).forEach { (q, a) ->
                    put(JSONObject().apply {
                        put("role", "user")
                        put("content", q)
                    })
                    put(JSONObject().apply {
                        put("role", "assistant")
                        put("content", a.take(1200))
                    })
                }
                put(JSONObject().apply {
                    put("role", "user")
                    put("content", userQuery)
                })
            }

            val body = JSONObject().apply {
                put("model", model)
                put("max_tokens", 1400)
                put("temperature", 0.35)
                if (disableReasoning) {
                    put("reasoning", JSONObject().put("enabled", false))
                }
                put("messages", messages)
            }.toString().toByteArray(StandardCharsets.UTF_8)

            val conn = (URL(endpoint).openConnection() as HttpURLConnection).apply {
                requestMethod = "POST"
                setRequestProperty("Content-Type", "application/json")
                if (apiKey.isNotBlank()) {
                    setRequestProperty("Authorization", "Bearer $apiKey")
                }
                setRequestProperty("HTTP-Referer", "https://fokk.app")
                setRequestProperty("X-Title", "Fokk Browser AI")
                connectTimeout = DEFAULT_CONNECT_TIMEOUT
                readTimeout = DEFAULT_READ_TIMEOUT
                doOutput = true
            }

            conn.outputStream.use { it.write(body) }

            if (conn.responseCode == HttpURLConnection.HTTP_OK) {
                val resp = conn.inputStream.bufferedReader(StandardCharsets.UTF_8).use { it.readText() }
                val json = JSONObject(resp)
                val choices = json.optJSONArray("choices") ?: return ""
                if (choices.length() == 0) return ""
                val message = choices.getJSONObject(0).optJSONObject("message") ?: return ""

                val text = message.optString("content", "").trim()
                if (text.isBlank() || text == "null") {
                    ""
                } else {
                    sanitizeLlmOutput(text)
                }
            } else {
                ""
            }
        } catch (_: Exception) {
            ""
        }
    }

