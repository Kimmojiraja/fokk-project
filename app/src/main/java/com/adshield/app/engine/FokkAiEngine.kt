    /**
     * Resolves the active AI API key (custom user key, build configuration, or built-in fallback).
     */
    fun resolveApiKey(context: Context): String {
        val prefs = context.getSharedPreferences("adshield_prefs", Context.MODE_PRIVATE)
        val customKey = prefs.getString("fokk_ai_api_key", "")?.trim().orEmpty()
        if (customKey.isNotBlank()) return customKey

        if (BuildConfig.FOKK_AI_KEY.isNotBlank()) return BuildConfig.FOKK_AI_KEY

        return try {
            String(Base64.decode(BUILTIN_FALLBACK_OR_KEY, Base64.DEFAULT), StandardCharsets.UTF_8).trim()
        } catch (_: Exception) {
            ""
        }
    }

    /**
     * Fixes newspaper drop-cap extraction artifacts like "W hen" -> "When", "T he" -> "The".
     */
    fun cleanDropCaps(text: String): String {
        if (text.isBlank()) return ""
        return text.replace(Regex("""\b([B-HJ-Z])\s+([a-z]{2,})\b""")) { m ->
            "${m.groupValues[1]}${m.groupValues[2]}"
        }
    }

    /**
     * Cleans chain-of-thought scratchpad notes and think blocks from LLM output.
     */
    fun sanitizeLlmOutput(raw: String): String {
        if (raw.isBlank()) return ""
        var s = raw.replace(Regex("(?s)<think>.*?</think>"), "")
        s = s.replace(Regex("(?is)^(\\*\\*)?thinking process:?(\\*\\*)?.*?\n\n"), "")
        s = s.replace(Regex("(?is)^(\\*\\*)?here('s| is) a thinking process:?(\\*\\*)?.*?\n\n"), "")
        s = s.replace(Regex("(?is)^we need (to )?answer as fokk ai.*?(\n\n|$)"), "")
        s = s.replace(Regex("(?is)^okay, let('s| us) analyze.*?(\n\n|$)"), "")
        s = s.replace(Regex("(?is)^let's think step by step.*?(\n\n|$)"), "")
        return stripEmojis(cleanDropCaps(s)).trim()
    }

